CREATE TABLE hsr_teams (
  team_id         VARCHAR2(20)  CONSTRAINT hsr_teams_pk PRIMARY KEY,
  team_name       VARCHAR2(60)  NOT NULL,
  sort_order      NUMBER(3)     DEFAULT 1 NOT NULL,
  off_mode        VARCHAR2(10)  DEFAULT 'ROTATE' NOT NULL
                  CONSTRAINT hsr_teams_mode_ck CHECK (off_mode IN ('ROTATE', 'FIXED', 'COVER')),
  min_on_duty     NUMBER(3)     DEFAULT 1 NOT NULL,
  offs_per_week   NUMBER(1)     DEFAULT 2 NOT NULL,
  fixed_off_days  VARCHAR2(30)  DEFAULT 'FRI,SAT',
  turn_days       NUMBER(2)     DEFAULT 4 NOT NULL,
  night_leader    CHAR(1)       DEFAULT 'N' NOT NULL CONSTRAINT hsr_teams_night_ck CHECK (night_leader IN ('Y', 'N')),
  night_time      VARCHAR2(10)  DEFAULT '10pm'
);
COMMENT ON COLUMN hsr_teams.off_mode IS
  'ROTATE = each person gets OFFS_PER_WEEK days off, spread so MIN_ON_DUTY stays on duty; FIXED = everyone off on FIXED_OFF_DAYS; COVER = MIN_ON_DUTY people work in turns of TURN_DAYS days';

CREATE TABLE hsr_staff (
  staff_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100)
               CONSTRAINT hsr_staff_pk PRIMARY KEY,
  staff_name   VARCHAR2(60)  NOT NULL,
  team_id      VARCHAR2(20)  NOT NULL CONSTRAINT hsr_staff_team_fk REFERENCES hsr_teams,
  post         VARCHAR2(40),
  shift_times  VARCHAR2(80)  DEFAULT '9am' NOT NULL,
  sort_order   NUMBER(4)     DEFAULT 1 NOT NULL,
  active       CHAR(1)       DEFAULT 'Y' NOT NULL CONSTRAINT hsr_staff_active_ck CHECK (active IN ('Y', 'N'))
);
COMMENT ON COLUMN hsr_staff.shift_times IS 'Default start time, e.g. 8pm. Several times separated by commas rotate day by day when shifts are distributed.';

CREATE TABLE hsr_codes (
  code      VARCHAR2(10)  CONSTRAINT hsr_codes_pk PRIMARY KEY,
  label_en  VARCHAR2(40)  NOT NULL,
  label_ar  VARCHAR2(60 CHAR),
  kind      VARCHAR2(10)  NOT NULL CONSTRAINT hsr_codes_kind_ck CHECK (kind IN ('OFF', 'LEAVE', 'DUTY')),
  colour    VARCHAR2(7)
);

CREATE TABLE hsr_periods (
  period_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100)
              CONSTRAINT hsr_periods_pk PRIMARY KEY,
  start_date  DATE      NOT NULL,
  num_days    NUMBER(2) NOT NULL CONSTRAINT hsr_periods_days_ck CHECK (num_days BETWEEN 1 AND 31),
  end_date    DATE GENERATED ALWAYS AS (start_date + num_days - 1) VIRTUAL,
  created_by  VARCHAR2(60),
  created_on  DATE DEFAULT SYSDATE,
  CONSTRAINT hsr_periods_start_uk UNIQUE (start_date)
);

CREATE TABLE hsr_roster (
  staff_id    NUMBER       NOT NULL CONSTRAINT hsr_roster_staff_fk REFERENCES hsr_staff ON DELETE CASCADE,
  duty_date   DATE         NOT NULL,
  period_id   NUMBER       NOT NULL CONSTRAINT hsr_roster_period_fk REFERENCES hsr_periods ON DELETE CASCADE,
  cell_value  VARCHAR2(20) NOT NULL,
  source      VARCHAR2(10) DEFAULT 'MANUAL' NOT NULL CONSTRAINT hsr_roster_source_ck CHECK (source IN ('MANUAL', 'AUTO', 'IMPORT')),
  updated_by  VARCHAR2(60),
  updated_on  DATE DEFAULT SYSDATE,
  CONSTRAINT hsr_roster_pk PRIMARY KEY (staff_id, duty_date)
);
CREATE INDEX hsr_roster_period_ix ON hsr_roster (period_id, duty_date);

CREATE TABLE hsr_shift_timings (
  timing_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT hsr_timings_pk PRIMARY KEY,
  label       VARCHAR2(60) NOT NULL,
  time_text   VARCHAR2(30) NOT NULL,
  sort_order  NUMBER(3) DEFAULT 1 NOT NULL
);

CREATE TABLE hsr_rules (
  rule_no    NUMBER(3) CONSTRAINT hsr_rules_pk PRIMARY KEY,
  rule_text  VARCHAR2(1000 CHAR) NOT NULL
);

CREATE TABLE hsr_app_users (
  user_name      VARCHAR2(60) CONSTRAINT hsr_users_pk PRIMARY KEY,
  full_name      VARCHAR2(80) NOT NULL,
  password_hash  VARCHAR2(64) NOT NULL,
  app_role       VARCHAR2(10) DEFAULT 'ADMIN' NOT NULL CONSTRAINT hsr_users_role_ck CHECK (app_role IN ('ADMIN', 'VIEWER')),
  active         CHAR(1) DEFAULT 'Y' NOT NULL CONSTRAINT hsr_users_active_ck CHECK (active IN ('Y', 'N'))
);
COMMENT ON COLUMN hsr_app_users.password_hash IS 'SHA-256 of UPPER(user_name) || '':'' || password, lowercase hex. The portal page uses the same rule.';

