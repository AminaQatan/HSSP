CREATE OR REPLACE PACKAGE BODY hsr_roster_pkg AS

  FUNCTION current_user_name RETURN VARCHAR2 IS
  BEGIN
    RETURN NVL(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER);
  END current_user_name;

  FUNCTION normalize_user (p_user IN VARCHAR2) RETURN VARCHAR2 DETERMINISTIC IS
  BEGIN
    RETURN UPPER(TRIM(REGEXP_REPLACE(p_user, '\s+', ' ')));
  END normalize_user;

  FUNCTION hash_password (p_user IN VARCHAR2, p_password IN VARCHAR2) RETURN VARCHAR2 IS
    l_hash VARCHAR2(64);
  BEGIN
    SELECT LOWER(RAWTOHEX(STANDARD_HASH(normalize_user(p_user) || ':' || p_password, 'SHA256')))
      INTO l_hash FROM dual;
    RETURN l_hash;
  END hash_password;

  FUNCTION authenticate (p_username IN VARCHAR2, p_password IN VARCHAR2) RETURN BOOLEAN IS
    l_hash hsr_app_users.password_hash%TYPE;
  BEGIN
    SELECT password_hash INTO l_hash
      FROM hsr_app_users
     WHERE user_name = normalize_user(p_username) AND active = 'Y';
    RETURN l_hash = hash_password(p_username, p_password);
  EXCEPTION
    WHEN NO_DATA_FOUND THEN RETURN FALSE;
  END authenticate;

  FUNCTION is_admin (p_user IN VARCHAR2) RETURN VARCHAR2 IS
    l_n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO l_n FROM hsr_app_users
     WHERE user_name = normalize_user(p_user) AND app_role = 'ADMIN' AND active = 'Y';
    RETURN CASE WHEN l_n > 0 THEN 'Y' ELSE 'N' END;
  END is_admin;

  PROCEDURE set_password (p_user IN VARCHAR2, p_new_password IN VARCHAR2) IS
  BEGIN
    IF LENGTH(p_new_password) < 6 OR p_new_password IS NULL THEN
      RAISE_APPLICATION_ERROR(-20001, 'Use at least 6 characters for the password.');
    END IF;
    UPDATE hsr_app_users SET password_hash = hash_password(p_user, p_new_password)
     WHERE user_name = normalize_user(p_user);
    IF SQL%ROWCOUNT = 0 THEN
      RAISE_APPLICATION_ERROR(-20002, 'There is no user called ' || p_user || '.');
    END IF;
  END set_password;

  PROCEDURE add_user (p_full_name IN VARCHAR2, p_password IN VARCHAR2, p_role IN VARCHAR2 DEFAULT 'ADMIN') IS
  BEGIN
    IF LENGTH(p_password) < 6 OR p_password IS NULL THEN
      RAISE_APPLICATION_ERROR(-20001, 'Use at least 6 characters for the password.');
    END IF;
    INSERT INTO hsr_app_users (user_name, full_name, password_hash, app_role)
    VALUES (normalize_user(p_full_name), TRIM(p_full_name), hash_password(p_full_name, p_password), UPPER(p_role));
  END add_user;

  FUNCTION to_minutes (p_time IN VARCHAR2) RETURN NUMBER DETERMINISTIC IS
    l_t  VARCHAR2(200) := LOWER(REPLACE(TRIM(SUBSTR(p_time, 1, 200)), ' '));
    l_h  NUMBER;
    l_m  NUMBER;
  BEGIN
    IF NOT REGEXP_LIKE(l_t, '^[0-9]{1,2}(:[0-9]{2})?\.?[ap]\.?m?\.?$') THEN
      RETURN NULL;
    END IF;
    l_h := TO_NUMBER(REGEXP_SUBSTR(l_t, '^[0-9]{1,2}'));
    l_m := NVL(TO_NUMBER(REGEXP_SUBSTR(l_t, ':([0-9]{2})', 1, 1, NULL, 1)), 0);
    IF l_h NOT BETWEEN 1 AND 12 THEN
      RETURN NULL;
    END IF;
    RETURN (MOD(l_h, 12) + CASE WHEN INSTR(l_t, 'p') > 0 THEN 12 ELSE 0 END) * 60 + l_m;
  END to_minutes;

  FUNCTION norm_time (p_time IN VARCHAR2) RETURN VARCHAR2 DETERMINISTIC IS
    l_min NUMBER := to_minutes(p_time);
    l_h   NUMBER;
  BEGIN
    IF l_min IS NULL THEN
      RETURN TRIM(p_time);
    END IF;
    l_h := MOD(TRUNC(l_min / 60), 12);
    RETURN CASE WHEN l_h = 0 THEN 12 ELSE l_h END
        || CASE WHEN MOD(l_min, 60) > 0 THEN ':' || LPAD(MOD(l_min, 60), 2, '0') END
        || CASE WHEN l_min >= 720 THEN 'pm' ELSE 'am' END;
  END norm_time;

  FUNCTION norm_value (p_value IN VARCHAR2) RETURN VARCHAR2 DETERMINISTIC IS
    l_v VARCHAR2(200) := TRIM(SUBSTR(p_value, 1, 200));
    l_u VARCHAR2(200) := UPPER(TRIM(SUBSTR(p_value, 1, 200)));
  BEGIN
    IF l_v IS NULL THEN RETURN NULL; END IF;
    IF l_u IN ('O', 'OFF') THEN RETURN 'O'; END IF;
    IF l_u IN ('C/OFF', 'COFF', 'C/O', 'C OFF') THEN RETURN 'C/OFF'; END IF;
    IF l_u IN ('AL', 'PH', 'PD') THEN RETURN l_u; END IF;
    IF l_u = 'WO' OR REGEXP_LIKE(l_u, '^WO[ /]') THEN
      RETURN 'WO/' || norm_time(TRIM(REGEXP_REPLACE(l_v, '^[Ww][Oo]\s*/?\s*', '')));
    END IF;
    RETURN norm_time(l_v);
  END norm_value;

  FUNCTION value_kind (p_value IN VARCHAR2) RETURN VARCHAR2 DETERMINISTIC IS
    l_v VARCHAR2(200) := norm_value(p_value);
  BEGIN
    RETURN CASE
             WHEN l_v IS NULL THEN 'NONE'
             WHEN l_v = 'O' THEN 'OFF'
             WHEN l_v IN ('AL', 'PH', 'PD', 'C/OFF') THEN 'LEAVE'
             ELSE 'DUTY'
           END;
  END value_kind;

  FUNCTION value_time (p_value IN VARCHAR2) RETURN VARCHAR2 DETERMINISTIC IS
    l_v VARCHAR2(200) := norm_value(p_value);
  BEGIN
    IF value_kind(l_v) <> 'DUTY' THEN RETURN NULL; END IF;
    RETURN CASE WHEN l_v LIKE 'WO/%' THEN SUBSTR(l_v, 4) ELSE l_v END;
  END value_time;

  FUNCTION time_bucket (p_minutes IN NUMBER) RETURN VARCHAR2 DETERMINISTIC IS
  BEGIN
    RETURN CASE
             WHEN p_minutes IS NULL THEN 'Other'
             WHEN p_minutes >= 300  AND p_minutes < 720  THEN 'Morning'
             WHEN p_minutes >= 720  AND p_minutes < 1020 THEN 'Afternoon'
             WHEN p_minutes >= 1020 AND p_minutes < 1260 THEN 'Evening'
             ELSE 'Night'
           END;
  END time_bucket;

  FUNCTION period_of (p_date IN DATE) RETURN NUMBER IS
    l_id NUMBER;
  BEGIN
    SELECT period_id INTO l_id FROM hsr_periods
     WHERE TRUNC(p_date) BETWEEN start_date AND end_date;
    RETURN l_id;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN RETURN NULL;
  END period_of;

  PROCEDURE set_cell (p_staff_id IN NUMBER, p_date IN DATE, p_value IN VARCHAR2, p_source IN VARCHAR2 DEFAULT 'MANUAL') IS
    l_value  VARCHAR2(200) := norm_value(p_value);
    l_period NUMBER := period_of(p_date);
    l_user   VARCHAR2(255) := current_user_name;
  BEGIN
    IF l_period IS NULL THEN
      RAISE_APPLICATION_ERROR(-20020, 'There is no roster period for ' || TO_CHAR(p_date, 'DD Mon YYYY') || '. Create the period first.');
    END IF;
    IF l_value IS NULL THEN
      DELETE FROM hsr_roster WHERE staff_id = p_staff_id AND duty_date = TRUNC(p_date);
      RETURN;
    END IF;
    MERGE INTO hsr_roster r
    USING (SELECT p_staff_id AS staff_id, TRUNC(p_date) AS duty_date FROM dual) x
       ON (r.staff_id = x.staff_id AND r.duty_date = x.duty_date)
     WHEN MATCHED THEN UPDATE SET r.cell_value = l_value, r.source = p_source, r.period_id = l_period,
                                  r.updated_by = l_user, r.updated_on = SYSDATE
     WHEN NOT MATCHED THEN INSERT (staff_id, duty_date, period_id, cell_value, source, updated_by)
                           VALUES (p_staff_id, TRUNC(p_date), l_period, l_value, p_source, l_user);
  END set_cell;

  PROCEDURE load_row (p_staff_id IN NUMBER, p_start IN DATE, p_values IN VARCHAR2, p_source IN VARCHAR2 DEFAULT 'IMPORT') IS
    l_rest  VARCHAR2(4000) := p_values || '|';
    l_pos   PLS_INTEGER;
    l_val   VARCHAR2(40);
    l_day   PLS_INTEGER := 0;
  BEGIN
    LOOP
      l_pos := INSTR(l_rest, '|');
      EXIT WHEN NVL(l_pos, 0) = 0;
      l_val  := SUBSTR(l_rest, 1, l_pos - 1);
      l_rest := SUBSTR(l_rest, l_pos + 1);
      IF TRIM(l_val) IS NOT NULL THEN
        set_cell(p_staff_id, p_start + l_day, l_val, p_source);
      END IF;
      l_day := l_day + 1;
    END LOOP;
  END load_row;

  FUNCTION create_period (p_start IN DATE, p_days IN NUMBER) RETURN NUMBER IS
    l_id    NUMBER;
    l_clash VARCHAR2(60);
    l_user  VARCHAR2(255) := current_user_name;
  BEGIN
    BEGIN
      SELECT TO_CHAR(start_date, 'DD Mon') || ' - ' || TO_CHAR(end_date, 'DD Mon YYYY') INTO l_clash
        FROM hsr_periods
       WHERE start_date <= TRUNC(p_start) + p_days - 1 AND end_date >= TRUNC(p_start)
       FETCH FIRST 1 ROW ONLY;
      RAISE_APPLICATION_ERROR(-20010, 'That period overlaps ' || l_clash || '. Pick a first day after it, or redistribute that period instead.');
    EXCEPTION
      WHEN NO_DATA_FOUND THEN NULL;
    END;
    INSERT INTO hsr_periods (start_date, num_days, created_by)
    VALUES (TRUNC(p_start), p_days, l_user)
    RETURNING period_id INTO l_id;
    RETURN l_id;
  END create_period;

  /* Automatic shift distribution. Same rules as the portal page:
       FIXED  : everyone in the team is off on FIXED_OFF_DAYS
       COVER  : MIN_ON_DUTY people work, in turns of TURN_DAYS days
       ROTATE : each person gets OFFS_PER_WEEK days off a week, two days
                together where possible, placed on the days with the most
                people to spare, about a week apart
     Leave already entered (AL, PH, PD, C/OFF) stays when p_keep_leave = 'Y'.
     Every value already entered stays when p_keep_entered = 'Y'.
     Working days get the person's SHIFT_TIMES (rotating if several); a team
     with NIGHT_LEADER = 'Y' gets one person on NIGHT_TIME each day.          */
  PROCEDURE auto_distribute (p_period_id IN NUMBER, p_keep_leave IN VARCHAR2 DEFAULT 'Y', p_keep_entered IN VARCHAR2 DEFAULT 'N') IS
    TYPE t_num  IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
    TYPE t_txt  IS TABLE OF VARCHAR2(80) INDEX BY PLS_INTEGER;
    TYPE t_flag IS TABLE OF BOOLEAN INDEX BY PLS_INTEGER;
    l_start   DATE;
    l_days    PLS_INTEGER;
    l_abs     PLS_INTEGER;
    m_id      t_num;  m_times t_txt;  m_cnt PLS_INTEGER;
    cell      t_txt;  keep_f t_flag;  off_f t_flag;
    on_duty   t_num;  pref t_num;     ord t_num;  avail_n t_num;
    placed    t_num;  night_n t_num;  workers t_num;  picked t_flag;
    l_need    PLS_INTEGER;  l_pc PLS_INTEGER;  l_wc PLS_INTEGER;
    l_per     PLS_INTEGER;  l_block PLS_INTEGER;  l_len PLS_INTEGER;  l_q PLS_INTEGER;
    l_turn    PLS_INTEGER;  l_want PLS_INTEGER;  l_slot PLS_INTEGER;
    l_best    PLS_INTEGER;  l_best_score NUMBER;  l_score NUMBER;  l_surplus NUMBER;  l_gap NUMBER;
    l_ok      BOOLEAN;      l_has BOOLEAN;
    l_night   NUMBER;       l_pick PLS_INTEGER;   l_tmp NUMBER;   l_m PLS_INTEGER;
    l_k       PLS_INTEGER;  l_dy VARCHAR2(3);     l_v VARCHAR2(40);  l_n PLS_INTEGER;

    FUNCTION k (p_m PLS_INTEGER, p_d PLS_INTEGER) RETURN PLS_INTEGER IS
    BEGIN
      RETURN p_m * 100 + p_d;
    END k;

    FUNCTION pick_time (p_times VARCHAR2, p_abs PLS_INTEGER) RETURN VARCHAR2 IS
      l_cnt PLS_INTEGER := REGEXP_COUNT(p_times, '[^,;]+');
    BEGIN
      IF l_cnt = 0 THEN RETURN '9am'; END IF;
      RETURN norm_time(TRIM(REGEXP_SUBSTR(p_times, '[^,;]+', 1, MOD(p_abs, l_cnt) + 1)));
    END pick_time;
  BEGIN
    SELECT start_date, num_days INTO l_start, l_days FROM hsr_periods WHERE period_id = p_period_id;
    l_abs := l_start - DATE '1970-01-01';

    FOR t IN (SELECT * FROM hsr_teams ORDER BY sort_order, team_id) LOOP
      m_id.DELETE; m_times.DELETE; cell.DELETE; keep_f.DELETE; off_f.DELETE;
      on_duty.DELETE; pref.DELETE; ord.DELETE; avail_n.DELETE; night_n.DELETE;
      m_cnt := 0;
      FOR s IN (SELECT staff_id, shift_times FROM hsr_staff
                 WHERE team_id = t.team_id AND active = 'Y' ORDER BY sort_order, staff_id) LOOP
        m_cnt := m_cnt + 1;
        m_id(m_cnt) := s.staff_id;
        m_times(m_cnt) := NVL(s.shift_times, '9am');
      END LOOP;
      CONTINUE WHEN m_cnt = 0;
      l_need := LEAST(GREATEST(NVL(t.min_on_duty, 0), 0), m_cnt);

      -- current values and what stays
      FOR m IN 1 .. m_cnt LOOP
        avail_n(m) := 0;
        FOR d IN 0 .. l_days - 1 LOOP
          BEGIN
            SELECT cell_value INTO l_v FROM hsr_roster WHERE staff_id = m_id(m) AND duty_date = l_start + d;
          EXCEPTION WHEN NO_DATA_FOUND THEN l_v := NULL;
          END;
          cell(k(m, d)) := l_v;
          keep_f(k(m, d)) := (value_kind(l_v) = 'LEAVE' AND p_keep_leave = 'Y')
                        OR (p_keep_entered = 'Y' AND value_kind(l_v) <> 'NONE');
          off_f(k(m, d)) := FALSE;
          IF NOT keep_f(k(m, d)) THEN avail_n(m) := avail_n(m) + 1; END IF;
        END LOOP;
      END LOOP;

      IF t.off_mode = 'FIXED' THEN
        FOR m IN 1 .. m_cnt LOOP
          FOR d IN 0 .. l_days - 1 LOOP
            l_dy := TO_CHAR(l_start + d, 'DY', 'NLS_DATE_LANGUAGE=ENGLISH');
            IF NOT keep_f(k(m, d)) AND INSTR(',' || UPPER(REPLACE(t.fixed_off_days, ' ')) || ',', ',' || l_dy || ',') > 0 THEN
              off_f(k(m, d)) := TRUE;
            END IF;
          END LOOP;
        END LOOP;

      ELSIF t.off_mode = 'COVER' THEN
        l_turn := LEAST(GREATEST(NVL(t.turn_days, 4), 1), 14);
        l_want := GREATEST(1, l_need);
        FOR d IN 0 .. l_days - 1 LOOP
          l_slot := FLOOR((l_abs + d) / l_turn);
          picked.DELETE; l_pc := 0;
          FOR j IN 0 .. m_cnt - 1 LOOP
            EXIT WHEN l_pc >= l_want;
            l_m := MOD(l_slot * l_want + j, m_cnt) + 1;
            IF NOT keep_f(k(l_m, d)) THEN
              l_pc := l_pc + 1; picked(l_m) := TRUE;
            END IF;
          END LOOP;
          FOR m IN 1 .. m_cnt LOOP
            IF NOT keep_f(k(m, d)) AND NOT picked.EXISTS(m) THEN off_f(k(m, d)) := TRUE; END IF;
          END LOOP;
        END LOOP;

      ELSE -- ROTATE
        l_per := LEAST(GREATEST(NVL(t.offs_per_week, 2), 0), 5);
        l_block := CASE WHEN l_per >= 2 THEN 2 ELSE 1 END;
        FOR d IN 0 .. l_days - 1 LOOP
          on_duty(d) := 0;
          FOR m IN 1 .. m_cnt LOOP
            IF NOT keep_f(k(m, d)) THEN on_duty(d) := on_duty(d) + 1; END IF;
          END LOOP;
        END LOOP;
        -- preferred weekday offset per person, and the order (fewest available days first, stable)
        FOR m IN 1 .. m_cnt LOOP
          pref(m) := MOD(ROUND((m - 1) * 7 / m_cnt), 7);
          ord(m) := m;
        END LOOP;
        FOR i IN 2 .. m_cnt LOOP
          l_tmp := ord(i); l_n := i - 1;
          WHILE l_n >= 1 AND avail_n(ord(l_n)) > avail_n(l_tmp) LOOP
            ord(l_n + 1) := ord(l_n); l_n := l_n - 1;
          END LOOP;
          ord(l_n + 1) := l_tmp;
        END LOOP;
        FOR i IN 1 .. m_cnt LOOP
          l_m := ord(i);
          l_q := ROUND(l_per * avail_n(l_m) / 7);
          placed.DELETE; l_pc := 0;
          WHILE l_q > 0 LOOP
            l_len := LEAST(l_block, l_q);
            l_best := -1; l_best_score := NULL;
            FOR st IN 0 .. l_days - l_len LOOP
              l_ok := TRUE; l_surplus := 0;
              FOR d IN st .. st + l_len - 1 LOOP
                IF keep_f(k(l_m, d)) OR off_f(k(l_m, d)) THEN l_ok := FALSE; EXIT; END IF;
                l_surplus := l_surplus + on_duty(d) - l_need;
              END LOOP;
              IF l_ok THEN
                l_score := LEAST(l_surplus, l_len * 2) * 10 + CASE WHEN l_surplus < 0 THEN l_surplus * 40 ELSE 0 END;
                IF l_pc > 0 THEN
                  l_gap := NULL;
                  FOR x IN 1 .. l_pc LOOP
                    IF l_gap IS NULL OR ABS(st - placed(x)) < l_gap THEN l_gap := ABS(st - placed(x)); END IF;
                  END LOOP;
                  l_score := l_score - ABS(l_gap - 7) * 4;
                  IF l_gap <= l_len THEN l_score := l_score - 60; END IF;
                ELSE
                  l_want := MOD(MOD(pref(l_m) - MOD(l_abs, 7), 7) + 7, 7);
                  l_score := l_score - LEAST(ABS(st - l_want), ABS(st - l_want - 7), ABS(st - l_want + 7)) * 3;
                END IF;
                IF l_best < 0 OR l_score > l_best_score THEN
                  l_best := st; l_best_score := l_score;
                END IF;
              END IF;
            END LOOP;
            EXIT WHEN l_best < 0;
            FOR d IN l_best .. l_best + l_len - 1 LOOP
              off_f(k(l_m, d)) := TRUE; on_duty(d) := on_duty(d) - 1;
            END LOOP;
            l_pc := l_pc + 1; placed(l_pc) := l_best;
            l_q := l_q - l_len;
          END LOOP;
        END LOOP;
      END IF;

      -- write days off and shift times; one night leader a day where asked
      l_night := to_minutes(NVL(t.night_time, '10pm'));
      FOR m IN 1 .. m_cnt LOOP night_n(m) := 0; END LOOP;
      FOR d IN 0 .. l_days - 1 LOOP
        workers.DELETE; l_wc := 0;
        FOR m IN 1 .. m_cnt LOOP
          l_k := k(m, d);
          IF keep_f(l_k) THEN
            IF to_minutes(value_time(cell(l_k))) = l_night THEN night_n(m) := night_n(m) + 1; END IF;
          ELSIF off_f(l_k) THEN
            cell(l_k) := 'O';
          ELSE
            cell(l_k) := pick_time(m_times(m), l_abs + d);
            l_wc := l_wc + 1; workers(l_wc) := m;
          END IF;
        END LOOP;
        IF t.night_leader = 'Y' AND l_night IS NOT NULL AND l_wc > 0 THEN
          l_has := FALSE;
          FOR m IN 1 .. m_cnt LOOP
            IF value_kind(cell(k(m, d))) = 'DUTY' AND to_minutes(value_time(cell(k(m, d)))) = l_night THEN l_has := TRUE; END IF;
          END LOOP;
          IF NOT l_has THEN
            l_pick := workers(1);
            FOR w IN 2 .. l_wc LOOP
              l_m := workers(w);
              IF night_n(l_m) < night_n(l_pick)
                 OR (night_n(l_m) = night_n(l_pick)
                     AND NVL(to_minutes(pick_time(m_times(l_m), 0)), 0) > NVL(to_minutes(pick_time(m_times(l_pick), 0)), 0)) THEN
                l_pick := l_m;
              END IF;
            END LOOP;
            cell(k(l_pick, d)) := norm_time(NVL(t.night_time, '10pm'));
            night_n(l_pick) := night_n(l_pick) + 1;
          ELSE
            FOR m IN 1 .. m_cnt LOOP
              IF NOT keep_f(k(m, d)) AND to_minutes(value_time(cell(k(m, d)))) = l_night THEN night_n(m) := night_n(m) + 1; END IF;
            END LOOP;
          END IF;
        END IF;
        FOR m IN 1 .. m_cnt LOOP
          IF NOT keep_f(k(m, d)) THEN
            set_cell(m_id(m), l_start + d, cell(k(m, d)), 'AUTO');
          END IF;
        END LOOP;
      END LOOP;
    END LOOP;
  END auto_distribute;

  PROCEDURE set_day_headings (p_period_id IN NUMBER, p_item_prefix IN VARCHAR2 DEFAULT 'P1_') IS
    l_start DATE;
    l_days  NUMBER;
    l_head  VARCHAR2(40);
  BEGIN
    SELECT start_date, num_days INTO l_start, l_days FROM hsr_periods WHERE period_id = p_period_id;
    FOR i IN 1 .. 31 LOOP
      l_head := CASE WHEN i <= l_days
                     THEN TO_CHAR(l_start + i - 1, 'FMDD Mon', 'NLS_DATE_LANGUAGE=ENGLISH') || ' ' ||
                          TO_CHAR(l_start + i - 1, 'DY', 'NLS_DATE_LANGUAGE=ENGLISH') END;
      -- called dynamically so the package also compiles where APEX is not installed
      EXECUTE IMMEDIATE 'begin apex_util.set_session_state(:1, :2); end;'
        USING p_item_prefix || 'H' || LPAD(i, 2, '0'), l_head;
    END LOOP;
  END set_day_headings;

END hsr_roster_pkg;
