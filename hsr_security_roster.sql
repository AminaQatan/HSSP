  FUNCTION  hash_password  (p_user IN VARCHAR2, p_password IN VARCHAR2) RETURN VARCHAR2;
  FUNCTION  authenticate   (p_username IN VARCHAR2, p_password IN VARCHAR2) RETURN BOOLEAN;
  FUNCTION  is_admin       (p_user IN VARCHAR2) RETURN VARCHAR2;
  PROCEDURE set_password   (p_user IN VARCHAR2, p_new_password IN VARCHAR2);
  PROCEDURE add_user       (p_full_name IN VARCHAR2, p_password IN VARCHAR2, p_role IN VARCHAR2 DEFAULT 'ADMIN');

  -- cell values
  FUNCTION  to_minutes     (p_time IN VARCHAR2) RETURN NUMBER DETERMINISTIC;
  FUNCTION  norm_time      (p_time IN VARCHAR2) RETURN VARCHAR2 DETERMINISTIC;
  FUNCTION  norm_value     (p_value IN VARCHAR2) RETURN VARCHAR2 DETERMINISTIC;
