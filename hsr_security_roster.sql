-- People on duty per team and day, against the team minimum
CREATE OR REPLACE VIEW hsr_daily_coverage_v AS
SELECT p.period_id, p.start_date + d.n AS duty_date,
       TO_CHAR(p.start_date + d.n, 'DY', 'NLS_DATE_LANGUAGE=ENGLISH') AS day_name,
       t.team_id, t.team_name, t.sort_order AS team_sort, t.min_on_duty,
       (SELECT COUNT(*) FROM hsr_roster_v v
         WHERE v.team_id = t.team_id AND v.duty_date = p.start_date + d.n AND v.kind = 'DUTY') AS on_duty,
       GREATEST(t.min_on_duty - (SELECT COUNT(*) FROM hsr_roster_v v
         WHERE v.team_id = t.team_id AND v.duty_date = p.start_date + d.n AND v.kind = 'DUTY'), 0) AS short_by
  FROM hsr_periods p
 CROSS JOIN (SELECT LEVEL - 1 AS n FROM dual CONNECT BY LEVEL <= 31) d
 CROSS JOIN hsr_teams t
 WHERE d.n < p.num_days
   AND EXISTS (SELECT 1 FROM hsr_staff s WHERE s.team_id = t.team_id AND s.active = 'Y');

